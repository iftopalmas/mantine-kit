import { describe, expect, test } from '@jest/globals';

import { exportLocale, exportMessages } from '@/src/export/ExportTexts';
import { GENERATED_AT } from '@/__test__/export/ExportFixture';

describe('ExportTexts', () => {
    test('uses the en-US texts by default', () => {
        const messages = exportMessages({});

        expect(exportLocale({})).toBe('en-US');
        expect(messages.generatedAt(GENERATED_AT)).toBe('Generated on 10/20/2026 at 2:30 PM');
        expect(messages.footer('System')).toBe('Data generated by System');
    });

    test('uses the texts of the locale of the document, with the ones it overrides', () => {
        const messages = exportMessages({ locale: 'pt-BR', messages: { footer: name => `Feito por ${name}` } });

        expect(messages.generatedAt(GENERATED_AT)).toBe('Gerado em 20/10/2026 às 14:30');
        expect(messages.footer('System')).toBe('Feito por System');
    });
});
