import { describe, expect, jest, test } from '@jest/globals';
import { screen } from '@testing-library/react';
import userEvent from '@testing-library/user-event';

import PrintSection from '@/src/component/molecule/PrintSection/PrintSection';
import PrintPage from '@/src/component/template/PrintPage/PrintPage';
import { KitProvider } from '@/src/provider/KitProvider';
import { render } from '@/test-utils';

const INFO = [
    { label: 'District', value: 'Palmas' },
    { label: 'Period', value: '2026 to 2035' }
];

describe('PrintPage', () => {
    test('shows the logo, the title, the generation date, the context and the footer with the link', async () => {
        render(
            <PrintPage systemName="My System" title="Test report" info={INFO} logo={<img alt="logo" />}>
                <p>content</p>
            </PrintPage>
        );

        expect(screen.getByRole('img', { name: 'logo' })).toBeInTheDocument();
        expect(screen.getByRole('heading', { level: 1, name: 'Test report' })).toBeInTheDocument();
        expect(await screen.findByText(/^Generated on \d{2}\/\d{2}\/\d{4} at /)).toBeInTheDocument();
        expect(screen.getByText('District:').parentElement).toHaveTextContent('District: Palmas');
        expect(screen.getByText('content')).toBeInTheDocument();
        expect(screen.getByText('Data generated by My System')).toBeInTheDocument();
        expect(screen.getByRole('link', { name: window.location.origin })).toHaveAttribute(
            'href',
            window.location.origin
        );
    });

    test('shows the texts in the locale of the app', async () => {
        render(
            <KitProvider locale="pt-BR">
                <PrintPage systemName="My System" title="Report">
                    content
                </PrintPage>
            </KitProvider>
        );

        expect(await screen.findByText(/^Gerado em \d{2}\/\d{2}\/\d{4} às \d{2}:\d{2}$/)).toBeInTheDocument();
        expect(screen.getByText('Dados gerados pelo My System')).toBeInTheDocument();
        expect(screen.getByRole('button', { name: 'Imprimir ou salvar como PDF' })).toBeInTheDocument();
    });

    test('opens the print dialog with the button, which stays out of the printed document', async () => {
        const print = jest.spyOn(window, 'print').mockImplementation(() => {});
        render(
            <PrintPage systemName="My System" title="Report">
                content
            </PrintPage>
        );

        const button = screen.getByRole('button', { name: 'Print or save as PDF' });
        await userEvent.click(button);

        expect(print).toHaveBeenCalledTimes(1);
        expect(button.closest('[data-print-hidden]')).not.toBeNull();
    });

    test('marks the paper orientation, used by the print CSS', () => {
        const { container } = render(
            <>
                <PrintPage systemName="My System" title="Portrait">
                    content
                </PrintPage>
                <PrintPage systemName="My System" title="Landscape" orientation="landscape">
                    content
                </PrintPage>
            </>
        );

        expect(container.querySelector('[data-print-orientation="portrait"]')).not.toBeNull();
        expect(container.querySelector('[data-print-orientation="landscape"]')).not.toBeNull();
    });
});

describe('PrintSection', () => {
    test('starts on a new page only when asked, and the title is not left alone at the end of a page', () => {
        render(
            <>
                <PrintSection title="First">a</PrintSection>
                <PrintSection title="Second" newPage>
                    b
                </PrintSection>
            </>
        );

        // The section is named after its title, for screen readers.
        expect(screen.getByRole('region', { name: 'First' })).not.toHaveAttribute('data-print-new-page');
        expect(screen.getByRole('region', { name: 'Second' })).toHaveAttribute('data-print-new-page');
        expect(screen.getByRole('heading', { name: 'Second' })).toHaveAttribute('data-print-keep-with-next');
    });
});
