/**
 * Model of the exported data, independent of the file format (see `ExportFormat`). An export is a document with one
 * or more sheets, and each sheet is a matrix (an array of arrays) of cells, with the title of each column.
 * It depends on no domain: whoever exports converts their data to this model.
 * @author Manoel Campos
 */

import { KitLocale } from '../i18n/KitLocale';
import { ExportMessages } from '../i18n/KitMessages';
import { DEFAULT_MESSAGES } from '../i18n/resolveMessages';

/** Format of a numeric value. Percentages are in the 0..1 scale and converted only for display. */
export type NumberFormat = {
    /** Decimal places shown. */
    decimals: number;

    /** Whether the value is a percentage in the 0..1 scale (e.g. 0.85 is shown as 85%). */
    percent?: boolean;
};

/** Number with its own format, for when the format changes from one row to another (e.g. the unit of each row). */
export type NumberCell = {
    value: number;
    format: NumberFormat;
};

/** Cell whose value could not be computed (e.g. a calculation error), unlike an empty (absent) cell. */
export type InvalidCell = {
    invalid: true;

    /** Text shown instead of the value. */
    text: string;
};

/**
 * Value of a cell:
 * - `string`: text;
 * - `number`: number, in the format of the column (`NaN` is treated as an absent value);
 * - {@link NumberCell}: number with its own format;
 * - {@link InvalidCell}: invalid result;
 * - `undefined`: absent value (empty cell), which is different from zero.
 */
export type ExportCell = string | number | NumberCell | InvalidCell | undefined;

/** Column of a sheet. */
export type ExportColumn = {
    /** Title (header) of the column. */
    header: string;

    /** Format of the numbers of the column, used when the cell has none; absent for {@link DEFAULT_NUMBER_FORMAT}. */
    format?: NumberFormat;
};

/** Sheet of the file: a table with the columns and the rows. */
export type ExportSheet = {
    /** Name of the sheet. Each format adapts it to its rules (e.g. the maximum length in Excel). */
    name: string;
    columns: ExportColumn[];

    /**
     * One array per row, with one cell per column, in the order of {@link columns}. A shorter row is completed with
     * empty cells; a row with more cells than columns is an error, since the extra data would be lost.
     */
    rows: ExportCell[][];
};

/** Information about the context of the data, shown at the beginning of the file (e.g. the period and the filters). */
export type ExportInfo = {
    label: string;
    value: string;
};

/** Visual identity of the system that generated the file, shown in the header and in the footer. */
export type ExportBranding = {
    /** Name of the system, shown in the footer (e.g. "Data generated by My System"). */
    systemName: string;

    /** Address of the system, shown as a link in the footer. */
    siteUrl: string;

    /** Logo shown in the header; absent to show no logo (e.g. if it could not be loaded). */
    logo?: ExportImage;
};

/** PNG image embedded in the file. */
export type ExportImage = {
    /** Content of the image, as a base64 data URL (`data:image/png;base64,...`). */
    pngDataUrl: string;

    /** Original width and height (px), to keep the aspect ratio when resizing. */
    width: number;
    height: number;
};

/** Document to export: the data and its context. */
export type ExportDocument = {
    /** Title shown at the top of the file. */
    title: string;

    /** Name of the file, without the date and the extension, which are added on export. */
    fileName: string;
    info: ExportInfo[];

    /** Date and time the data was generated. */
    generatedAt: Date;
    branding: ExportBranding;
    sheets: ExportSheet[];

    /** Locale of the texts and of the number format of the file. Default: `en-US`. */
    locale?: KitLocale;

    /** Texts that replace the ones of the locale (e.g. the ones the app overrides in the `KitProvider`). */
    messages?: Partial<ExportMessages>;
};

/** Format of the numbers of a column that defines none. */
export const DEFAULT_NUMBER_FORMAT: NumberFormat = { decimals: 2 };

/** Types of cell, after being normalized by {@link classifyCell}. */
export type ClassifiedCell =
    | { kind: 'empty' }
    | { kind: 'text'; text: string }
    | { kind: 'number'; value: number; format: NumberFormat }
    | { kind: 'invalid'; text: string };

/**
 * Creates a cell with an invalid result.
 * @param text text shown instead of the value; defaults to the text of the default locale
 * @return the invalid cell
 */
export function invalidCell(text: string = DEFAULT_MESSAGES.export.invalidCell): InvalidCell {
    return { invalid: true, text };
}

/**
 * Tells whether the cell is an invalid result.
 * @param cell cell to check
 */
export function isInvalidCell(cell: ExportCell): cell is InvalidCell {
    return typeof cell === 'object' && 'invalid' in cell;
}

/**
 * Classifies a cell, so that every format handles each type of value the same way. A `NaN` number is treated as
 * absent (empty cell), and `Infinity` as invalid (e.g. a division by zero).
 * @param cell cell to classify
 * @param columnFormat format of the column of the cell, used when the cell is a number without its own format
 * @param invalidText text of an infinite number; defaults to the text of the default locale
 * @return the type and the value of the cell
 */
export function classifyCell(
    cell: ExportCell,
    columnFormat: NumberFormat = DEFAULT_NUMBER_FORMAT,
    invalidText: string = DEFAULT_MESSAGES.export.invalidCell
): ClassifiedCell {
    if (cell === undefined) return { kind: 'empty' };
    if (typeof cell === 'string') return { kind: 'text', text: cell };
    if (isInvalidCell(cell)) return { kind: 'invalid', text: cell.text };

    const { value, format } = typeof cell === 'number' ? { value: cell, format: columnFormat } : cell;
    if (Number.isNaN(value)) return { kind: 'empty' };
    if (!Number.isFinite(value)) return { kind: 'invalid', text: invalidText };

    return { kind: 'number', value, format };
}
