/** Past tense of the form action verbs (e.g. "Create" → "created"), used in the success message. */
const PAST_TENSE: Record<string, string> = { create: 'created', update: 'updated', view: 'viewed' };

/**
 * Returns the past tense of a form action verb.
 * @param action verb, as in `form.action`
 * @return the past tense, in lower case; for an unknown verb, the verb itself followed by "d"
 */
function pastTense(action: string): string {
    const verb = action.toLowerCase();

    return PAST_TENSE[verb] ?? `${verb}d`;
}
