'use client';

import { ReactElement, ReactNode, useEffect, useState } from 'react';

import { Alert, Anchor, Box, Button, Group, Stack, Text, Title } from '@mantine/core';
import { IconInfoCircle, IconPrinter } from '@tabler/icons-react';

import type { ExportInfo } from '../../../export/ExportDocument';
import { useLightColorSchemeOnPrint } from '../../../hook/useLightColorSchemeOnPrint';
import { PrintMessages } from '../../../i18n/KitMessages';
import { useKitMessages } from '../../../provider/useKit';

/** Size of the icons (px). */
const ICON_SIZE = 18;

/** Paper orientation: portrait (default) or landscape, for wide tables (e.g. a year per column). */
export type PrintOrientation = 'portrait' | 'landscape';

type Props = {
    /** Title of the report, shown in the header. */
    title: string;

    /** Context info shown below the title (e.g. the period and the filters). */
    info?: ExportInfo[];

    orientation?: PrintOrientation;

    /** Name of the system, shown in the footer (e.g. "Data generated by My System"). */
    systemName: string;

    /** Logo shown on the left of the title (e.g. an `<img>` about 48 px high); absent to show none. */
    logo?: ReactNode;

    /** Content of the report: sections ({@link PrintSection}), tables and charts. */
    children: ReactNode;
};

/**
 * Common layout of the reports: an HTML page formatted to be printed or saved as PDF with the browser itself.
 * It has the logo, the title, the generation date, the context and, at the end, a footer with the link of the system.
 * The bar with the "Print" button and the tips of the print dialog is shown only on screen. The pagination (paper size,
 * repeated table header, page numbers) comes from the `styles/print.css` of the library.
 */
function PrintPage({ title, info = [], orientation = 'portrait', systemName, logo, children }: Props): ReactElement {
    useLightColorSchemeOnPrint();
    const messages = useKitMessages();

    /* The generation date and the address of the system are read only in the browser, after mounting: on the server,
       the date would be another one and there is no `window`, so the HTML would differ from the one of the browser
       (hydration error). */
    const [generatedAt, setGeneratedAt] = useState<Date>();
    const [siteUrl, setSiteUrl] = useState('');
    useEffect(() => {
        setGeneratedAt(new Date());
        setSiteUrl(window.location.origin);
    }, []);

    return (
        <Box data-print-orientation={orientation} p={{ base: 'xs', sm: 'md' }}>
            <PrintToolbar messages={messages.print} />

            <Stack component="header" gap={4} mb="lg">
                <Group gap="sm" wrap="nowrap">
                    {logo}
                    <Title order={1} size="h2" c="var(--mantine-primary-color-filled)">
                        {title}
                    </Title>
                </Group>
                {generatedAt && (
                    <Text size="sm" c="dimmed" fs="italic">
                        {messages.export.generatedAt(generatedAt)}
                    </Text>
                )}
                {info.map(item => (
                    <Text key={item.label} size="sm">
                        <Text span fw={700} c="dimmed">
                            {item.label}:
                        </Text>{' '}
                        {item.value}
                    </Text>
                ))}
            </Stack>

            {children}

            <Stack component="footer" gap={0} mt="xl" data-print-block>
                <Text size="xs" c="dimmed">
                    {messages.export.footer(systemName)}
                </Text>
                {siteUrl && (
                    <Anchor href={siteUrl} size="xs">
                        {siteUrl}
                    </Anchor>
                )}
            </Stack>
        </Box>
    );
}

/** Bar shown only on screen, with the print button and the tips about the options of the print dialog. */
function PrintToolbar({ messages }: { messages: PrintMessages }): ReactElement {
    return (
        <Group data-print-hidden justify="space-between" align="flex-start" mb="md" wrap="wrap">
            <Alert
                variant="light"
                icon={<IconInfoCircle size={ICON_SIZE} />}
                title={messages.pdfTipTitle}
                style={{ flex: 1, minWidth: 280 }}
            >
                {messages.pdfTip}
            </Alert>
            <Button leftSection={<IconPrinter size={ICON_SIZE} />} onClick={() => window.print()}>
                {messages.printButton}
            </Button>
        </Group>
    );
}

export default PrintPage;
